import {it,expect,vi,afterEach} from 'vitest';
import {createApp,nextTick,type App} from 'vue';
import {createPinia} from 'pinia';
const mocks=vi.hoisted(()=>({search:vi.fn(async()=>({items:[{kind:'note',id:'doc',label:'needle result',path:'/notes?doc=doc'}]})),push:vi.fn(async()=>{}),auth:{me:{id:'owner'}}}));
vi.mock('../../api/notes',async()=>{const original=await vi.importActual<any>('../../api/notes');return {...original,unifiedSearch:mocks.search};});
vi.mock('vue-router',()=>({useRouter:()=>({push:mocks.push})}));
vi.mock('../home/auth',()=>({auth:mocks.auth,refreshAccess:vi.fn(async()=>false)}));
let app:App|undefined;
afterEach(()=>{app?.unmount();app=undefined;document.body.innerHTML='';localStorage.clear();vi.clearAllMocks();});
it('Cmd/Ctrl+K searches current-workspace metadata and modules without creating a note',async()=>{
 const components=import.meta.glob('./CommandPalette.vue');
 expect(components['./CommandPalette.vue'],'global search component exists').toBeTypeOf('function');
 const mod:any=await components['./CommandPalette.vue']!();
 localStorage.setItem('stella_bootstrap',JSON.stringify({userId:'owner',workspaceId:'current-workspace'}));
 const root=document.createElement('div');document.body.append(root);
 app=createApp(mod.default,{modules:[{label:'自定义图库',path:'/gallery'}]}).use(createPinia());app.mount(root);
 window.dispatchEvent(new KeyboardEvent('keydown',{key:'k',metaKey:true,bubbles:true,cancelable:true}));await nextTick();
 expect(document.querySelector('[role=dialog]')).not.toBeNull();
 expect(document.body.textContent).toContain('自定义图库');
 const input=document.querySelector<HTMLInputElement>('[aria-label="统一搜索"]')!;
 input.value='needle';input.dispatchEvent(new Event('input',{bubbles:true}));
 await new Promise(r=>setTimeout(r,260));await nextTick();
 expect(mocks.search).toHaveBeenCalledWith('needle','current-workspace',expect.any(AbortSignal));
 expect(document.body.textContent).toContain('needle result');
 window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));await nextTick();
 expect(document.querySelector('[role=dialog]')).toBeNull();
 window.dispatchEvent(new KeyboardEvent('keydown',{key:'k',ctrlKey:true,bubbles:true,cancelable:true}));await nextTick();
 expect(document.querySelector('[role=dialog]')).not.toBeNull();
});
